package org.firstinspires.ftc.teamcode.bobot.utlities;

public class MyMath {

    public static double pifagor(double a, double b) {
        return Math.sqrt(a * a + b * b);
    }
    public static double sqrt(double a){
        return Math.sqrt(a);
    }
     
    public static double arcTan(double tanValue) {
        return Math.toDegrees(Math.atan(tanValue));
    }
     
}

